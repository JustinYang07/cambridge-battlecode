#!/usr/bin/env python3
"""Train the camp-choice ranker: a shared scorer (NF -> H -> 1, ReLU) with a softmax over each
sample's candidate camps. Held out by game. Writes weights as a C++ header.

usage: train_farm.py <data.npz> <out_header.h> [--hidden 16] [--epochs 60]
"""
import sys
import numpy as np

data = np.load(sys.argv[1]); OUT = sys.argv[2]
H = int(sys.argv[sys.argv.index('--hidden') + 1]) if '--hidden' in sys.argv else 16
EPOCHS = int(sys.argv[sys.argv.index('--epochs') + 1]) if '--epochs' in sys.argv else 60
X, off, y, game, mp = data['X'], data['off'], data['y'], data['game'], data['map']
N, NF = len(y), X.shape[1]
rng = np.random.default_rng(1)
games = np.unique(game); rng.shuffle(games)
test_games = set(games[: max(1, len(games) // 5)])
is_test = np.array([g in test_games for g in game])
mu = X.mean(0); sd = X.std(0) + 1e-6
Xn = (X - mu) / sd
seg = np.repeat(np.arange(N), np.diff(off))

def forward(P, idx_rows):
    W1, b1, w2, b2 = P
    h = np.maximum(0, Xn[idx_rows] @ W1 + b1)
    return h, h @ w2 + b2

def loss_grad(P, samples):
    rows = np.concatenate([np.arange(off[i], off[i + 1]) for i in samples])
    sg = np.concatenate([np.full(off[i + 1] - off[i], k) for k, i in enumerate(samples)])
    h, s = forward(P, rows)
    # softmax per sample
    smax = np.full(len(samples), -1e9); np.maximum.at(smax, sg, s)
    e = np.exp(s - smax[sg]); z = np.zeros(len(samples)); np.add.at(z, sg, e)
    p = e / z[sg]
    target = np.zeros(len(rows)); target[np.array([off[i] + y[i] for i in samples]) - np.repeat(off[samples], 1) + np.concatenate([[0], np.cumsum(np.diff(off)[samples])[:-1]])] = 1
    loss = -np.sum(np.log(p[target == 1] + 1e-12)) / len(samples)
    g = (p - target) / len(samples)
    W1, b1, w2, b2 = P
    gw2 = h.T @ g; gb2 = g.sum()
    gh = np.outer(g, w2) * (h > 0)
    gW1 = Xn[rows].T @ gh; gb1 = gh.sum(0)
    return loss, [gW1, gb1, gw2, gb2]

def accuracy(P, samples):
    hits = 0
    for i in samples:
        _, s = forward(P, np.arange(off[i], off[i + 1]))
        hits += int(np.argmax(s) == y[i])
    return hits / max(1, len(samples))

def train(hidden):
    P = [rng.normal(0, 0.3, (NF, hidden)), np.zeros(hidden), rng.normal(0, 0.3, hidden), np.zeros(())] if hidden else None
    m = [np.zeros_like(p) for p in P]; v = [np.zeros_like(p) for p in P]
    tr = np.where(~is_test)[0]; lr = 0.01; t = 0
    for ep in range(EPOCHS):
        rng.shuffle(tr)
        for k in range(0, len(tr), 256):
            loss, G = loss_grad(P, tr[k:k + 256]); t += 1
            for j in range(4):
                m[j] = 0.9 * m[j] + 0.1 * G[j]; v[j] = 0.999 * v[j] + 0.001 * G[j] ** 2
                P[j] = P[j] - lr * (m[j] / (1 - 0.9 ** t)) / (np.sqrt(v[j] / (1 - 0.999 ** t)) + 1e-8)
    return P

te = np.where(is_test)[0]; trs = np.where(~is_test)[0]
near = np.mean([np.argmin(X[off[i]:off[i + 1], 0]) == y[i] for i in te])
print(f'samples {N} (train {len(trs)}, test {len(te)} from {len(test_games)} games), avg candidates {np.diff(off).mean():.1f}')
print(f'baseline nearest camp: test top-1 {near:.3f}')
P = train(H)
print(f'MLP {NF}->{H}->1: train {accuracy(P, trs[:3000]):.3f} test {accuracy(P, te):.3f}')
for m_ in np.unique(mp[te]):
    sub = te[mp[te] == m_]
    print(f'   {m_:12s} test n={len(sub):4d} mlp {accuracy(P, sub):.3f} nearest {np.mean([np.argmin(X[off[i]:off[i+1],0])==y[i] for i in sub]):.3f}')
W1, b1, w2, b2 = P
def arr(a): return ', '.join(f'{float(x):.6g}f' for x in np.ravel(a))
with open(OUT, 'w') as f:
    f.write('#pragma once\n// Generated by lab/nn/train_farm.py: camp-choice ranker imitating the top team.\n')
    f.write(f'// {N} samples; test top-1 {accuracy(P, te):.3f} (nearest camp {near:.3f}).\n#include <array>\n\nnamespace nnfarm {{\n\n')
    f.write(f'inline constexpr int kIn = {NF}, kHidden = {H};\n')
    f.write(f'inline constexpr std::array<float, kIn> kMean{{{arr(mu)}}};\n')
    f.write(f'inline constexpr std::array<float, kIn> kStd{{{arr(sd)}}};\n')
    f.write(f'inline constexpr std::array<float, kIn * kHidden> kW1{{{arr(W1)}}};  // row-major [in][hidden]\n')
    f.write(f'inline constexpr std::array<float, kHidden> kB1{{{arr(b1)}}};\n')
    f.write(f'inline constexpr std::array<float, kHidden> kW2{{{arr(w2)}}};\n')
    f.write(f'inline constexpr float kB2 = {float(b2):.6g}f;\n\n')
    f.write('// Score of one candidate camp from its raw features (higher: more likely the top team goes there).\n')
    f.write('inline float score(const std::array<float, kIn>& x) {\n    std::array<float, kHidden> h{};\n    for (int j = 0; j < kHidden; ++j) h[j] = kB1[j];\n')
    f.write('    for (int i = 0; i < kIn; ++i) {\n        const float v = (x[i] - kMean[i]) / kStd[i];\n        for (int j = 0; j < kHidden; ++j) h[j] += v * kW1[i * kHidden + j];\n    }\n')
    f.write('    float s = kB2;\n    for (int j = 0; j < kHidden; ++j) s += (h[j] > 0 ? h[j] : 0.0f) * kW2[j];\n    return s;\n}\n\n} // namespace nnfarm\n')
print('wrote', OUT)
