#!/usr/bin/env python3
"""Train the "recall now" classifier (NF -> H -> 1, ReLU, logistic output). Held out by game.
usage: train_recall.py <data.npz> <out_header.h> [--hidden 8] [--epochs 20]"""
import sys
import numpy as np
d = np.load(sys.argv[1]); OUT = sys.argv[2]
H = int(sys.argv[sys.argv.index('--hidden') + 1]) if '--hidden' in sys.argv else 8
EP = int(sys.argv[sys.argv.index('--epochs') + 1]) if '--epochs' in sys.argv else 20
X, y, g = d['X'], d['y'].astype(np.float64), d['game']
NF = X.shape[1]; rng = np.random.default_rng(2)
games = np.unique(g); rng.shuffle(games); test = np.isin(g, games[: len(games) // 5])
mu, sd = X.mean(0), X.std(0) + 1e-6; Xn = (X - mu) / sd
pos_w = (1 - y[~test].mean()) / y[~test].mean()
P = [rng.normal(0, 0.3, (NF, H)), np.zeros(H), rng.normal(0, 0.3, H), np.zeros(())]
m = [np.zeros_like(p) for p in P]; v = [np.zeros_like(p) for p in P]; t = 0
tr = np.where(~test)[0]
def fwd(P, A):
    h = np.maximum(0, A @ P[0] + P[1]); return h, h @ P[2] + P[3]
for ep in range(EP):
    rng.shuffle(tr)
    for k in range(0, len(tr), 1024):
        b = tr[k:k + 1024]; h, z = fwd(P, Xn[b]); p = 1 / (1 + np.exp(-z))
        wgt = np.where(y[b] == 1, pos_w, 1.0); gz = wgt * (p - y[b]) / len(b)
        G = [Xn[b].T @ (np.outer(gz, P[2]) * (h > 0)), (np.outer(gz, P[2]) * (h > 0)).sum(0), h.T @ gz, gz.sum()]
        t += 1
        for j in range(4):
            m[j] = 0.9 * m[j] + 0.1 * G[j]; v[j] = 0.999 * v[j] + 0.001 * G[j] ** 2
            P[j] = P[j] - 0.003 * (m[j] / (1 - 0.9 ** t)) / (np.sqrt(v[j] / (1 - 0.999 ** t)) + 1e-8)
def auc(score, lab):
    o = np.argsort(score); r = np.empty(len(score)); r[o] = np.arange(len(score))
    npos = lab.sum(); return (r[lab == 1].sum() - npos * (npos - 1) / 2) / (npos * (len(lab) - npos))
_, zt = fwd(P, Xn[test]); yt = y[test]
print(f'turns {len(y)}, recall rate {y.mean()*100:.2f}%; test AUC net {auc(zt, yt):.3f} | rule low health {auc(-X[test,0], yt):.3f} | health+bag {auc(-X[test,0]+X[test,1], yt):.3f}')
for q in (0.5, 0.8, 0.9):
    thr = np.quantile(zt, 1 - yt.mean() * (1 / q))  # flag as many turns as recalls / q
    flag = zt >= thr
    print(f'  flag {flag.mean()*100:.2f}% of turns: precision {yt[flag].mean():.3f}, recall {yt[flag].sum()/yt.sum():.3f}')
# decision threshold: logit where flagged rate equals the true recall rate
thr = float(np.quantile(zt, 1 - yt.mean()))
def arr(a): return ', '.join(f'{float(x):.6g}f' for x in np.ravel(a))
with open(OUT, 'w') as f:
    f.write('#pragma once\n// Generated by lab/nn/train_recall.py: "recall now" classifier imitating the top team.\n')
    f.write(f'// test AUC {auc(zt, yt):.3f} (low health alone {auc(-X[test,0], yt):.3f}).\n#include <array>\n\nnamespace nnrecall {{\n\n')
    f.write(f'inline constexpr int kIn = {NF}, kHidden = {H};\ninline constexpr float kThreshold = {thr:.6g}f;  // logit where flagged turns match the recall rate\n')
    for nm, a in (('kMean', mu), ('kStd', sd)): f.write(f'inline constexpr std::array<float, kIn> {nm}{{{arr(a)}}};\n')
    f.write(f'inline constexpr std::array<float, kIn * kHidden> kW1{{{arr(P[0])}}};\ninline constexpr std::array<float, kHidden> kB1{{{arr(P[1])}}};\n')
    f.write(f'inline constexpr std::array<float, kHidden> kW2{{{arr(P[2])}}};\ninline constexpr float kB2 = {float(P[3]):.6g}f;\n\n')
    f.write('inline float logit(const std::array<float, kIn>& x) {\n    std::array<float, kHidden> h{};\n    for (int j = 0; j < kHidden; ++j) h[j] = kB1[j];\n')
    f.write('    for (int i = 0; i < kIn; ++i) {\n        const float v = (x[i] - kMean[i]) / kStd[i];\n        for (int j = 0; j < kHidden; ++j) h[j] += v * kW1[i * kHidden + j];\n    }\n')
    f.write('    float s = kB2;\n    for (int j = 0; j < kHidden; ++j) s += (h[j] > 0 ? h[j] : 0.0f) * kW2[j];\n    return s;\n}\n\n} // namespace nnrecall\n')
print('wrote', OUT)
