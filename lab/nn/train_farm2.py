#!/usr/bin/env python3
"""Camp-choice ranker distilled from several top teams (farm_dataset.py with a team list). A shared scorer
(NF -> H -> 1, ReLU) with a softmax over each sample's candidate camps; trained on --teams, held out by game.
Then on --compare (our team): how often our next camp matches its pick, and how the camps differ.
Writes the same header as train_farm.py (namespace nnfarm), so brain/farm.cpp uses it unchanged.
usage: train_farm2.py <data.npz> [--out header.h] [--teams "A,B"] [--compare bbas] [--hidden 16] [--epochs 6]"""
import sys
import numpy as np
arg = lambda k, d: sys.argv[sys.argv.index(k) + 1] if k in sys.argv else d
data = np.load(sys.argv[1]); OUT = arg('--out', '')
TEAMS = arg('--teams', 'Intercontinental Fish,Mite,Univardisty of Shingtonwash,Sneaky Bush Campers,Nyx').split(',')
COMPARE = arg('--compare', 'bbas'); H = int(arg('--hidden', '16')); EPOCHS = int(arg('--epochs', '6'))
X, off, y, game, team = data['X'], data['off'], data['y'], data['game'], data['team']
N, NF = len(y), X.shape[1]
NAMES = ['dist/30', 'strength', 'health', 'gems', 'gold', 'my hp', 'my bag', 'allies at camp', 'enemies at camp', 'our half',
         'to our spawn', 'round', 'reward', 'respawn wait', 'allies by me', 'last target', 'my max hp', 'enemies by me', 'heading']
rng = np.random.default_rng(1)
top = np.isin(team, TEAMS); ours = team == COMPARE
games = np.unique(game[top]); rng.shuffle(games)
test = top & np.isin(game, games[: len(games) // 5]); train = top & ~test
mu = X.mean(0); sd = X.std(0) + 1e-6; Xn = ((X - mu) / sd).astype(np.float32)
cnt = np.diff(off); seg = np.repeat(np.arange(N), cnt)
chosen_row = off[:-1] + y


def scores(P, rows=None):
    W1, b1, w2, b2 = P
    A = Xn if rows is None else Xn[rows]
    return np.maximum(0, A @ W1 + b1) @ w2 + b2


def pick(P, samples):
    s = scores(P)
    best = np.empty(N, dtype=np.int64)
    # argmax within each sample's candidate block
    order = np.lexsort((-s, seg)); first = np.r_[0, np.cumsum(cnt)[:-1]]
    best[:] = order[first] - off[:-1]
    return best[samples]


P = [rng.normal(0, 0.3, (NF, H)), np.zeros(H), rng.normal(0, 0.3, H), np.zeros(())]
m = [np.zeros_like(p) for p in P]; v = [np.zeros_like(p) for p in P]; t = 0
tr = np.where(train)[0]
for ep in range(EPOCHS):
    rng.shuffle(tr)
    for k in range(0, len(tr), 512):
        smp = tr[k:k + 512]
        rows = np.concatenate([np.arange(off[i], off[i + 1]) for i in smp]); sg = np.repeat(np.arange(len(smp)), cnt[smp])
        W1, b1, w2, b2 = P
        h = np.maximum(0, Xn[rows] @ W1 + b1); s = h @ w2 + b2
        mx = np.full(len(smp), -1e9); np.maximum.at(mx, sg, s)
        e = np.exp(s - mx[sg]); z = np.zeros(len(smp)); np.add.at(z, sg, e); p = e / z[sg]
        tgt = np.zeros(len(rows)); tgt[np.r_[0, np.cumsum(cnt[smp])[:-1]] + y[smp]] = 1
        g = (p - tgt) / len(smp)
        gh = np.outer(g, w2) * (h > 0)
        G = [Xn[rows].T @ gh, gh.sum(0), h.T @ g, g.sum()]
        t += 1
        for j in range(4):
            m[j] = 0.9 * m[j] + 0.1 * G[j]; v[j] = 0.999 * v[j] + 0.001 * G[j] ** 2
            P[j] = P[j] - 0.005 * (m[j] / (1 - 0.9 ** t)) / (np.sqrt(v[j] / (1 - 0.999 ** t)) + 1e-8)

te = np.where(test)[0]; ou = np.where(ours)[0]
nearest = lambda smp: np.array([np.argmin(X[off[i]:off[i + 1], 0]) for i in smp])
acc = (pick(P, te) == y[te]).mean(); nacc = (nearest(te) == y[te]).mean()
print(f'{train.sum()} train / {len(te)} test samples ({len(games)} top-team games), {cnt.mean():.1f} candidates on average')
print(f'  held-out top teams: top-1 {acc:.3f} (nearest camp {nacc:.3f})')
po = pick(P, ou); match = po == y[ou]
print(f'{COMPARE}: {len(ou)} samples, match {match.mean():.3f} (nearest camp {(nearest(ou) == y[ou]).mean():.3f})')
print('  feature means of the camp chosen:  top teams | ours | the policy\'s pick for us')
cho_top = X[chosen_row[te]]; cho_us = X[chosen_row[ou]]; pol_us = X[off[:-1][ou] + po]
for j, n in enumerate(NAMES):
    print(f'    {n:15s} {cho_top[:, j].mean():8.3f} | {cho_us[:, j].mean():8.3f} | {pol_us[:, j].mean():8.3f}')

if OUT:
    W1, b1, w2, b2 = P
    def lit(x):
        s = f'{float(x):.6g}'
        return (s if ('.' in s or 'e' in s or 'n' in s) else s + '.0') + 'f'
    arr = lambda a: ', '.join(lit(x) for x in np.ravel(a))
    with open(OUT, 'w') as f:
        f.write('#pragma once\n// Generated by lab/nn/train_farm2.py: camp-choice ranker distilled from ' + ', '.join(TEAMS) + '.\n')
        f.write(f'// {train.sum()} samples; held-out top-1 {acc:.3f} (nearest camp {nacc:.3f}).\n#include <array>\n\nnamespace nnfarm {{\n\n')
        f.write(f'inline constexpr int kIn = {NF}, kHidden = {H};\n')
        f.write(f'inline constexpr std::array<float, kIn> kMean{{{arr(mu)}}};\ninline constexpr std::array<float, kIn> kStd{{{arr(sd)}}};\n')
        f.write(f'inline constexpr std::array<float, kIn * kHidden> kW1{{{arr(W1)}}};  // row-major [in][hidden]\n')
        f.write(f'inline constexpr std::array<float, kHidden> kB1{{{arr(b1)}}};\ninline constexpr std::array<float, kHidden> kW2{{{arr(w2)}}};\n')
        f.write(f'inline constexpr float kB2 = {lit(b2)};\n\n')
        f.write('// Score of one candidate camp from its raw features (higher: more likely the top teams go there).\n')
        f.write('inline float score(const std::array<float, kIn>& x) {\n    std::array<float, kHidden> h{};\n    for (int j = 0; j < kHidden; ++j) h[j] = kB1[j];\n')
        f.write('    for (int i = 0; i < kIn; ++i) {\n        const float v = (x[i] - kMean[i]) / kStd[i];\n        for (int j = 0; j < kHidden; ++j) h[j] += v * kW1[i * kHidden + j];\n    }\n')
        f.write('    float s = kB2;\n    for (int j = 0; j < kHidden; ++j) s += (h[j] > 0 ? h[j] : 0.0f) * kW2[j];\n    return s;\n}\n\n} // namespace nnfarm\n')
    print('wrote', OUT)
