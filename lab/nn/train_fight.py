#!/usr/bin/env python3
"""Fight-engagement models on fight_engage_dataset.py rows (NF -> H -> 1, ReLU, logistic). Held out by game.
Targets: bad (we lose more champions than they do within 15 rounds), good (they lose more),
         engage (the team moved in over 3 rounds; use --team to imitate one team).
usage: train_fight.py [--csv lab/data/fights.csv] [--target bad] [--team NAME] [--min-rating R]
                      [--hidden 16] [--epochs 30] [--out header.h]
H=0 fits a logistic regression. Prints test AUC for H=0 and H, and a simple numbers/health rule."""
import csv, os, sys
import numpy as np
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
arg = lambda k, d: sys.argv[sys.argv.index(k) + 1] if k in sys.argv else d
CSV = arg('--csv', f'{ROOT}/lab/data/fights.csv'); TARGET = arg('--target', 'bad'); TEAM = arg('--team', '')
H = int(arg('--hidden', '16')); EP = int(arg('--epochs', '30')); OUT = arg('--out', ''); MINR = float(arg('--min-rating', '0'))
META = {'game', 'map', 'round', 'team', 'opp', 'rating', 'oppRating', 'won', 'ourDeaths', 'theirDeaths', 'hpTrade', 'approach'}

rows = list(csv.DictReader(open(CSV)))
if TEAM: rows = [r for r in rows if r['team'] == TEAM]
if MINR: rows = [r for r in rows if float(r['oppRating'] or 0) >= MINR]
# --bot: only what a champion can compute in game (no fog-hidden team totals or kill counts).
FOG = {'usAlive', 'themAlive', 'killsUs', 'killsThem', 'teamMaxHpUs', 'teamMaxHpThem', 'teamShardsUs', 'teamShardsThem'}
FEATS = [k for k in rows[0] if k not in META and not ('--bot' in sys.argv and k in FOG)]
X = np.array([[float(r[k]) for k in FEATS] for r in rows])
od = np.array([float(r['ourDeaths']) for r in rows]); td = np.array([float(r['theirDeaths']) for r in rows])
ap = np.clip(np.array([float(r['approach']) for r in rows]), -3, 3)
y = {'bad': od > td, 'good': td > od, 'engage': ap < -0.5}[TARGET].astype(np.float64)
g = np.array([r['game'] for r in rows])
rng = np.random.default_rng(3); games = np.unique(g); rng.shuffle(games)
test = np.isin(g, games[: len(games) // 5])
mu, sd = X[~test].mean(0), X[~test].std(0) + 1e-6; Xn = (X - mu) / sd
NF = X.shape[1]


def train(H, l2=1e-4):
    r = np.random.default_rng(1)
    hid = max(H, 1)
    P = [r.normal(0, 0.3, (NF, hid)), np.zeros(hid), r.normal(0, 0.3, hid), np.zeros(())]
    if H == 0: P = [np.zeros((NF, 1)), np.zeros(1), np.ones(1), np.zeros(())]
    m = [np.zeros_like(p) for p in P]; v = [np.zeros_like(p) for p in P]; t = 0
    tr = np.where(~test)[0]
    for _ in range(EP):
        r.shuffle(tr)
        for k in range(0, len(tr), 512):
            b = tr[k:k + 512]; h, z = fwd(P, Xn[b], H); p = 1 / (1 + np.exp(-z))
            gz = (p - y[b]) / len(b)
            gh = np.outer(gz, P[2]) * ((h > 0) if H else 1)
            G = [Xn[b].T @ gh + l2 * P[0], gh.sum(0), (h.T @ gz if H else np.zeros(1)), gz.sum()]
            t += 1
            for j in range(4):
                m[j] = 0.9 * m[j] + 0.1 * G[j]; v[j] = 0.999 * v[j] + 0.001 * G[j] ** 2
                P[j] = P[j] - 0.003 * (m[j] / (1 - 0.9 ** t)) / (np.sqrt(v[j] / (1 - 0.999 ** t)) + 1e-8)
    return P


def fwd(P, A, H):
    pre = A @ P[0] + P[1]
    h = np.maximum(0, pre) if H else pre
    return h, h @ P[2] + P[3]


def auc(score, lab):
    o = np.argsort(score); rk = np.empty(len(score)); rk[o] = np.arange(len(score))
    npos = lab.sum(); return (rk[lab == 1].sum() - npos * (npos - 1) / 2) / (npos * (len(lab) - npos))


def logloss(z, lab):
    p = np.clip(1 / (1 + np.exp(-z)), 1e-6, 1 - 1e-6); return -np.mean(lab * np.log(p) + (1 - lab) * np.log(1 - p))


yt = y[test]
fi = {k: i for i, k in enumerate(FEATS)}
rule = (X[:, fi['us8']] - X[:, fi['them8']]) + (X[:, fi['hpUs8']] - X[:, fi['hpThem8']])
sign = -1 if TARGET == 'bad' else 1
print(f'{len(y)} rows ({len(games)} games), {TARGET} rate {y.mean():.3f}, {NF} features' + (f', team {TEAM}' if TEAM else ''))
print(f'  rule (count + health edge): test AUC {auc(sign * rule[test], yt):.3f}')
res = {}
for h in (0, H):
    P = train(h); _, zt = fwd(P, Xn[test], h); res[h] = (P, zt)
    base = np.full(len(yt), np.log(y[~test].mean() / (1 - y[~test].mean())))
    print(f'  {"logistic" if h == 0 else f"net H={h}":10s} test AUC {auc(zt, yt):.3f}, log loss {logloss(zt, yt):.4f} (base rate {logloss(base, yt):.4f})')
P0 = res[0][0]
w = P0[0][:, 0] * P0[2][0]
print('  strongest logistic weights (per SD):', ', '.join(f'{FEATS[i]} {w[i]:+.2f}' for i in np.argsort(-np.abs(w))[:12]))

if OUT:
    P, zt = res[H]
    def lit(x):
        t = f'{float(x):.6g}'
        return (t if ('.' in t or 'e' in t or 'n' in t) else t + '.0') + 'f'
    def arr(a): return ', '.join(lit(x) for x in np.ravel(a))
    with open(OUT, 'w') as f:
        f.write(f'#pragma once\n// Generated by lab/nn/train_fight.py --target {TARGET}{" --team " + TEAM if TEAM else ""}: test AUC {auc(zt, yt):.3f}.\n')
        f.write('// Inputs (in order): ' + ', '.join(FEATS) + '\n#include <array>\n\nnamespace nnfight {\n\n')
        f.write(f'inline constexpr int kIn = {NF}, kHidden = {H};\n')
        for nm, a in (('kMean', mu), ('kStd', sd)): f.write(f'inline constexpr std::array<float, kIn> {nm}{{{arr(a)}}};\n')
        f.write(f'inline constexpr std::array<float, kIn * kHidden> kW1{{{arr(P[0])}}};\ninline constexpr std::array<float, kHidden> kB1{{{arr(P[1])}}};\n')
        f.write(f'inline constexpr std::array<float, kHidden> kW2{{{arr(P[2])}}};\ninline constexpr float kB2 = {lit(P[3])};\n\n')
        f.write('inline float logit(const std::array<float, kIn>& x) {\n    std::array<float, kHidden> h{};\n    for (int j = 0; j < kHidden; ++j) h[j] = kB1[j];\n')
        f.write('    for (int i = 0; i < kIn; ++i) {\n        const float v = (x[i] - kMean[i]) / kStd[i];\n        for (int j = 0; j < kHidden; ++j) h[j] += v * kW1[i * kHidden + j];\n    }\n')
        f.write('    float s = kB2;\n    for (int j = 0; j < kHidden; ++j) s += (h[j] > 0 ? h[j] : 0.0f) * kW2[j];\n    return s;\n}\n\n} // namespace nnfight\n')
    print('wrote', OUT)
